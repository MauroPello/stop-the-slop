#!/usr/bin/env node
/**
 * Build a caption-verified YouTube benchmark corpus.
 *
 * This intentionally labels only provenance that can be inferred before a
 * detector sees the transcript:
 *   human — a TED speaker presentation (known human performer)
 *   ai — title declares an AI-generated/AI-made/AI-assisted content work
 *
 * Run: node build-dataset.mjs
 */
import { mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { promisify } from 'node:util';
import { execFile } from 'node:child_process';

const exec = promisify(execFile);
const root = new URL('.', import.meta.url);
const output = new URL('./dataset.json', root);
// The benchmark is binary: 500 human controls and 500 AI-content works. It
// reuses prior stored transcripts and only caption-checks newly sourced rows.
// Legacy "mixed" entries were reviewed individually: content works become AI;
// software, tutorials, news, and process commentary are excluded.
const TARGETS = { human: 500, ai: 500 };
const CAPTION_CONCURRENCY = 3;
const captionFailures = new Map();
const humanSearches = [
  'TED talk science', 'TED talk health', 'TED talk psychology', 'TED talk technology',
  'TED talk business', 'TED talk education', 'TED talk society', 'TED talk creativity',
  'TED talk environment', 'TED talk history', 'TED talk leadership', 'TED talk relationships',
  'TEDx talk science', 'TEDx talk health', 'TEDx talk technology', 'TEDx talk society',
  'TEDx talk business', 'TEDx talk psychology',
];

const searches = {
  ai: [
    '"AI generated" "narrated"', '"AI generated" "AI voice"',
    '"AI generated" "full story"', '"AI narrator" story',
    '"AI narrated" story', '"using an AI Generated Voice"',
    '"AI-generated" short film', '"AI generated" animation',
    '"AI made" short film', '"AI-made" animation',
    '"created by AI" short film', '"made by AI" animation',
    '"generated by AI" story', '"generated with AI" narration',
    '"AI voice" documentary', '"AI narrated" documentary',
    '"AI generated" documentary', '"AI created" music video',
  ],
  assisted: [
    '"AI-assisted" short film', '"AI assisted" short film',
    '"made with AI" short film', '"created with AI" animation',
    '"AI-assisted" film', '"AI assisted" film',
    '"AI-assisted" music video', '"AI assisted" music video',
    '"made with AI" animation', '"made with AI" video',
  ],
};

// These legacy mixed rows were individually reviewed and removed because they
// describe tooling, instruction, commentary, news, or a hybrid workflow rather
// than an AI content work. Every other legacy mixed row is an identified film,
// animation, trailer, or music-video work and is relabelled as AI.
const REVIEWED_MIXED_DROP_IDS = new Set([
  'CMtD6Zzr4XQ', '8E5gsXVoiX0', 'R3pJ2HHFaTo', 'mBSMj4YvJqs',
  'pdEOGt_i4ck', 'aZu-4a6HQA4', 'Y14P2gn3rE4', 'V-dLlbPbzy4',
  'G3pUNA5VFwc', 'G0Z9QifF4C8', 'QfgDo82bGbQ', 'VcwXI40FDfk',
  '1M6RqtYEca0', 'RlKg6oXLf7Y', 'P0U6ExdIHxs', 'MHjvClvIwwg',
  'GgSKHAs3e5g', 'xql3lLn-yco', 'BGes2CcOKZk', 'fgSf1vGscQI',
  'wkO5WpqrUIE', 'tb8PM3RqK0I', 'spDM3bhkv9Y', 'FRnKY-5TqOM',
  'vd3oaD1u63w', 'lZBv4vBLrx4',
]);

function parseJsonLines(stdout) {
  return stdout.split('\n').filter(Boolean).flatMap((line) => {
    try { return [JSON.parse(line)]; } catch { return []; }
  });
}

async function list(url, limit) {
  const { stdout } = await exec('yt-dlp', [
    '--flat-playlist', '--playlist-end', String(limit), '--dump-json', url,
  ], { maxBuffer: 20 * 1024 * 1024, timeout: 180_000 });
  return parseJsonLines(stdout)
    .filter((v) => /^[\w-]{11}$/.test(v.id) && v.duration >= 60 && !v.live_status)
    .map((v) => ({ id: v.id, title: v.title.replace(/\s+/g, ' ').trim(), channel: v.channel || v.playlist_uploader || 'Unknown' }));
}

function isAiContentWork(title) {
  const lower = title.toLowerCase();
  if (/\b(how to|tutorial|workflow|guide|course|learn|explained|review|tips|tool|software|generator|feature highlights|production experience|filmmaking control|commentary|allowed in film festivals)\b/.test(lower)) return false;
  if (/\b(news|rejects film|behind the lens|inside my .*process)\b/.test(lower)) return false;
  const declared = /\b(ai[ -]?(generated|made|created|narrated|voice|assisted)|(?:generated|made|created) (?:by|with) ai|ai (short film|drama|animation|music video|narrator))\b/.test(lower);
  const content = /\b(short film|film|movie|animation|animated|trailer|music video|folktale|anime|cartoon|story)\b/.test(lower);
  return declared && content;
}

async function hasEnglishCaptions(videoId) {
  const dir = await mkdtemp(join(tmpdir(), 'sts-caption-'));
  try {
    await exec('yt-dlp', [
      '--cookies-from-browser', 'chrome',
      '--write-auto-sub', '--write-sub', '--sub-langs', 'en', '--sub-format', 'json3',
      '--skip-download', '--no-warnings', '--quiet', '-o', join(dir, '%(id)s.%(ext)s'),
      `https://www.youtube.com/watch?v=${videoId}`,
    ], { timeout: 45_000 });
    const names = await readdir(dir);
    const subtitle = names.find((name) => name.endsWith('.en.json3'));
    if (!subtitle) return false;
    const data = JSON.parse(await readFile(join(dir, subtitle), 'utf8'));
    const text = (data.events || []).flatMap((e) => e.segs || []).map((s) => s.utf8 || '').join(' ').trim();
    return text.length >= 50;
  } catch (error) {
    const message = `${error?.stderr || ''}\n${error?.message || ''}`;
    const reason = /\b429\b|too many requests/i.test(message)
      ? 'rate-limited'
      : /private|unavailable|not available/i.test(message)
        ? 'unavailable'
        : /subtitles|subtitle/i.test(message)
          ? 'no English subtitles'
          : 'download error';
    captionFailures.set(reason, (captionFailures.get(reason) || 0) + 1);
    return false;
  }
  finally { await rm(dir, { recursive: true, force: true }); }
}

async function captionFilter(candidates, target, label) {
  const accepted = [];
  const acceptedTitles = new Set();
  let next = 0;
  async function worker() {
    while (next < candidates.length && accepted.length < target) {
      const candidate = candidates[next++];
      if (await hasEnglishCaptions(candidate.id) && !acceptedTitles.has(candidate.title)) {
        acceptedTitles.add(candidate.title);
        accepted.push(candidate);
      }
      process.stderr.write(`\r${label}: ${accepted.length}/${target} checked ${next}/${candidates.length}`);
    }
  }
  await Promise.all(Array.from({ length: CAPTION_CONCURRENCY }, worker));
  process.stderr.write('\n');
  if (captionFailures.size) console.log(`Caption rejections: ${[...captionFailures].map(([reason, count]) => `${reason}=${count}`).join(', ')}`);
  return accepted.slice(0, target);
}

function entry(video, label, category, evidence) {
  return {
    videoId: video.id,
    url: `https://www.youtube.com/watch?v=${video.id}`,
    label,
    category,
    title: video.title,
    channel: video.channel,
    note: evidence,
  };
}

async function main() {
  // Keep only rows with a saved, usable transcript. This avoids re-fetching the
  // completed 500-row corpus and protects it from temporary YouTube throttles.
  const priorDataset = JSON.parse(await readFile(output, 'utf8'));
  let priorResults = {};
  try { priorResults = JSON.parse(await readFile(new URL('./results.json', root), 'utf8')); } catch { }
  const hasStoredTranscript = (video) => priorResults[video.videoId]?.transcript?.fullText?.length >= 50;
  const retainedHuman = priorDataset
    .filter((video) => video.label === 'human' && hasStoredTranscript(video));
  const retainedAi = priorDataset
    .filter((video) => video.label === 'ai' && hasStoredTranscript(video))
    .map((video) => ({ ...video, label: 'ai', category: 'declared_ai_generated' }));
  const reviewedMixedAsAi = priorDataset
    .filter((video) => video.label === 'mixed' && !REVIEWED_MIXED_DROP_IDS.has(video.videoId) && hasStoredTranscript(video))
    .map((video) => ({
      ...video,
      label: 'ai',
      category: 'reviewed_ai_content',
      note: 'Individually reviewed legacy mixed row: title identifies an AI-assisted or AI-made content work; English transcript was retained from the prior verified corpus.',
    }));
  const retained = [...retainedHuman, ...retainedAi, ...reviewedMixedAsAi];
  const retainedIds = new Set(retained.map((video) => video.videoId));
  console.log(`Retained stored transcripts: human=${retainedHuman.length}, ai=${retainedAi.length + reviewedMixedAsAi.length}`);

  const humanCandidates = [];
  const humanSeen = new Set();
  for (const query of humanSearches) {
    for (const video of await list(`ytsearch100:${query}`, 100)) {
      // Search returns adjacent channels too; retain only official TED/TEDx uploads.
      if ((video.channel === 'TED' || video.channel === 'TEDx Talks') && !retainedIds.has(video.id) && !humanSeen.has(video.id)) {
        humanSeen.add(video.id);
        humanCandidates.push(video);
      }
    }
  }
  const aiCandidates = [];
  const aiSeen = new Set();
  for (const [kind, queries] of Object.entries(searches)) {
    for (const query of queries) {
      // AI content is caption-scarce, so search deeply enough to maintain a
      // reserve after live subtitle checks.
      for (const video of await list(`ytsearch200:${query}`, 200)) {
        if (!retainedIds.has(video.id) && !REVIEWED_MIXED_DROP_IDS.has(video.id) && !aiSeen.has(video.id) && isAiContentWork(video.title)) {
          aiSeen.add(video.id);
          aiCandidates.push(video);
        }
      }
    }
  }

  const neededHuman = TARGETS.human - retainedHuman.length;
  const neededAi = TARGETS.ai - retainedAi.length - reviewedMixedAsAi.length;
  console.log(`Candidate inventory: human=${humanCandidates.length}, ai=${aiCandidates.length}; needed: human=${neededHuman}, ai=${neededAi}`);
  if (neededHuman < 0 || neededAi < 0) {
    throw new Error('Retained rows exceed a target; adjust TARGETS before building.');
  }
  if (humanCandidates.length < neededHuman || aiCandidates.length < neededAi) {
    throw new Error('Insufficient candidates before caption verification; expand the affected search pool.');
  }

  const human = await captionFilter(humanCandidates, neededHuman, 'human');
  const ai = await captionFilter(aiCandidates, neededAi, 'ai');
  const groups = {
    human: [...retainedHuman, ...human.map((v) => entry(v, 'human', 'speaker_presentation', 'TED presentation: identified human speaker; English captions verified at build time.'))],
    ai: [
      ...retainedAi,
      ...reviewedMixedAsAi,
      ...ai.map((v) => entry(v, 'ai', 'declared_ai_content', 'Title explicitly declares an AI-generated, AI-made, AI-narrated, or AI-assisted content work; English captions verified at build time.')),
    ],
  };
  const dataset = [...groups.human, ...groups.ai];
  if (dataset.length !== 1000) throw new Error(`Expected 1,000 rows, got ${dataset.length}`);
  await writeFile(output, `${JSON.stringify(dataset, null, 2)}\n`);
  console.log(JSON.stringify(Object.fromEntries(Object.entries(groups).map(([k, v]) => [k, v.length]))));
}

main().catch((error) => { console.error(error); process.exit(1); });
